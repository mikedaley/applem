std::vector<uint8_t> buildNoSignalFrame(int width, int height, const std::string &machine) {
  std::vector<uint8_t> buffer(static_cast<size_t>(width) * height * 4, 0);
  for (size_t i = 3; i < buffer.size(); i += 4) buffer[i] = 0xff;

  auto plot = [&](int x, int y, const uint8_t *rgb) {
    if (x < 0 || y < 0 || x >= width || y >= height) return;
    uint8_t *pixel = &buffer[(static_cast<size_t>(y) * width + x) * 4];
    pixel[0] = rgb[0];
    pixel[1] = rgb[1];
    pixel[2] = rgb[2];
  };

  auto drawTextCentred = [&](const std::string &text, int top, const uint8_t *rgb, int scale) {
    const int cellW = CELL_W * scale;
    int x = static_cast<int>(std::lround((width - static_cast<int>(text.size()) * cellW) / 2.0));
    for (char ch : text) {
      auto found = font().find(ch);
      const Glyph &glyph = found != font().end() ? found->second : font().at(' ');
      for (int row = 0; row < GLYPH_H; row++) {
        for (int col = 0; col < GLYPH_W; col++) {
          if (!(glyph[row] & (1 << (GLYPH_W - 1 - col)))) continue;
          const int block = PIXEL * scale;
          for (int dy = 0; dy < block; dy++) {
            for (int dx = 0; dx < block; dx++) {
              plot(x + col * block + dx, top + row * block + dy, rgb);
            }
          }
        }
      }
      x += cellW;
    }
  };

  // Rows snapped to whole character cells, on the text screen's grid. There
  // is deliberately no power symbol: it only invited clicks on a picture.
  auto cellRow = [](int row) { return row * CELL_H; };
  drawTextCentred("NO SIGNAL", cellRow(9), FG, 2);
  const size_t columns = static_cast<size_t>(width / CELL_W);
  const std::string message = "SWITCH ON THE APPLE " + machine + " TO START";
  if (message.size() <= columns) {
    drawTextCentred(message, cellRow(14), DIM, 1);
  } else {
    drawTextCentred("SWITCH ON THE APPLE " + machine, cellRow(14), DIM, 1);
    drawTextCentred("TO START", cellRow(16), DIM, 1);
  }
  return buffer;
}

std::string noSignalMachineName(const std::string &profileName) {
  std::string name = profileName;
  if (name.rfind("Apple", 0) == 0) {
    name = name.substr(5);
    while (!name.empty() && name.front() == ' ') name.erase(name.begin());
  }
  for (char &c : name) c = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
  return name.empty() ? "IIE" : name;
}

