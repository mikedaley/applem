constexpr int GLYPH_W = 5;
constexpr int GLYPH_H = 7;
// One Apple pixel is two framebuffer pixels each way, so a character cell
// matches the 7x8 cell of the real 40-column text screen.
constexpr int PIXEL = 2;
constexpr int CELL_W = 7 * PIXEL;
constexpr int CELL_H = 8 * PIXEL;

// Composite white is never paper white: this is the level the machine's own
// text sits at, so the message matches what appears a moment later.
constexpr uint8_t FG[3] = {0xe8, 0xe8, 0xe8};
constexpr uint8_t DIM[3] = {0x8c, 0x8c, 0x8c};

